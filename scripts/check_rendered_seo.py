#!/usr/bin/env python3
"""Post-build SEO invariants that source-only gates cannot see.

Checks the rendered `_site/` rather than the templates:

* exactly one `<h1>` per page (the 2026-10 double-H1 defect);
* every non-home page's `<title>` ends with the site name;
* every local `og:image` points at a file that was actually built;
* every JSON-LD block parses as JSON;
* every node typed `Dataset` carries the fields Google validates it against:
  `name` and `description` are required, `creator` and `license` are the two
  warnings the 2026-10-31 Search Console report raised on /scholarly-records/.

Redirect stubs generated by `redirect_from` intentionally carry no site title
and no H1, and are skipped.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "_site"
SITE_NAME = "The Andalusian Project Archive"
SKIP_TITLE = {"index.html", "404.html"}
DATASET_FIELDS = ("name", "description", "creator", "license")


def walk_jsonld(node):
    """Yield every object in a parsed JSON-LD value, depth first."""
    if isinstance(node, dict):
        yield node
        for value in node.values():
            yield from walk_jsonld(value)
    elif isinstance(node, list):
        for value in node:
            yield from walk_jsonld(value)


def missing_dataset_fields(node):
    """Return the Dataset fields that are absent or empty."""
    missing = []
    for field in DATASET_FIELDS:
        value = node.get(field)
        if value is None or value == "" or value == [] or value == {}:
            missing.append(field)
    return missing


def main() -> int:
    if not SITE.is_dir():
        print("FAIL: _site/ is missing; run `bundle exec jekyll build` first")
        return 1
    pages = sorted(SITE.rglob("*.html"))
    problems = []
    checked = 0

    for page in pages:
        rel = page.relative_to(SITE).as_posix()
        text = page.read_text(encoding="utf-8", errors="replace")
        if "http-equiv=\"refresh\"" in text and "Redirecting" in text:
            continue
        checked += 1

        h1 = len(re.findall(r"<h1\b", text))
        if h1 != 1:
            problems.append(f"{rel}: {h1} <h1> elements")

        title = re.search(r"<title>(.*?)</title>", text, re.S)
        if title and rel not in SKIP_TITLE:
            value = title.group(1).strip()
            if value != SITE_NAME and not value.endswith(" | " + SITE_NAME):
                problems.append(f"{rel}: title lacks site name: {value[:100]}")

        for match in re.finditer(r'<meta property="og:image" content="([^"]+)"', text):
            url = match.group(1)
            marker = "/andalusian-archive/"
            if marker in url:
                local = SITE / url.split(marker, 1)[1]
                if not local.exists():
                    problems.append(f"{rel}: og:image 404: {url}")

        for match in re.finditer(r'<script type="application/ld\+json">(.*?)</script>', text, re.S):
            try:
                data = json.loads(match.group(1))
            except json.JSONDecodeError as exc:
                problems.append(f"{rel}: invalid JSON-LD: {exc}")
                continue

            for node in walk_jsonld(data):
                types = node.get("@type")
                if types == "Dataset" or (isinstance(types, list) and "Dataset" in types):
                    missing = missing_dataset_fields(node)
                    if missing:
                        name = str(node.get("name", "(unnamed)"))[:80]
                        problems.append(
                            f"{rel}: Dataset {name!r} missing {', '.join(missing)}"
                        )

    if problems:
        for problem in problems[:40]:
            print(f"FAIL: {problem}")
        if len(problems) > 40:
            print(f"... and {len(problems) - 40} more")
        print(f"check_rendered_seo: {len(problems)} problem(s) across {checked} pages")
        return 1

    print(f"check_rendered_seo: {checked} pages checked; one H1, branded titles, "
          f"local og:images present, JSON-LD parses, Datasets complete")
    return 0


if __name__ == "__main__":
    sys.exit(main())
